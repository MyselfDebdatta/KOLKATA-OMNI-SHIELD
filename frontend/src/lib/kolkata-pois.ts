export function searchPois(q: string, limit = 12): { label: string; shortLabel: string; lat: number; lng: number }[] {
  const s = q.trim().toLowerCase();
  if (s.length < 2) return [];
  const scored: { poi: Poi; score: number }[] = [];
  for (const p of KOLKATA_POIS) {
    const hay = (p.name + " " + (p.aliases?.join(" ") ?? "")).toLowerCase();
    if (!hay.includes(s)) continue;
    const idx = hay.indexOf(s);
    const exact = hay.startsWith(s) ? 0 : idx;
    scored.push({ poi: p, score: exact });
  }
  scored.sort((a, b) => a.score - b.score);
  return scored.slice(0, limit).map(({ poi }) => ({
    label: `${poi.name} · Kolkata`,
    shortLabel: poi.name,
    lat: poi.lat,
    lng: poi.lng,
  }));
}
